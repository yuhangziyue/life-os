// 引导式回顾问题库 —— 空白框是世界上最难回答的问题（晓雅 X4）。
// 本地内置、零 AI 依赖；每期按周期序号轮换 3 题，答其中一个就够了。
//
// ============ v3.7 B6：这三池被重新筛了一遍，换掉 8 题 ============
// 为什么这时候才筛：月与年那两个 tab **从来没有独立入口**，等于**从未被真正打开过**，
// 于是那两池问题从写下那天起就没被检验过。B6 给了它们独立入口，它们才第一次要见人。
//
// 三层各问什么（Lisa 第四轮定的轴）：
//   **周问去处，月问分法，年问代价。**
//   · 周 = 行为尺度。一周内人能准确回忆做了什么，可以问事实
//   · 月 = 模式尺度。单次行为不重要，重复才重要。
//     **周问"去了哪"（召回），月问"这是你要的吗"（判断）——
//     判断只能在有模式的尺度上问；在一周的尺度上问判断，会让用户为一次波动下结论。**
//   · 年 = 取舍尺度。一年之后人不记得行为，只记得**故事**，
//     而人给自己讲的年度故事默认版本几乎总是审判。所以年题必须**已预设取舍框架**。
//
// 两条筛题规矩（以后谁供稿都照它）：
//   ① **搬得动的题不合格**：一道题换成周或年都成立 ⇒ 它没有绑住这个尺度，是泛问。
//   ② **年尺度上，「最」只许指向一件事、一段时间、一个人，不许指向「你」**（书香定的）。
//      「今年最大的成长」= 判决。「今年最不后悔的那一段」= 指认。
//      **差别就在「最」后面接的是什么。**
//
// 筛题时念的那一句（Lisa 六问表第 6 问）：把这句话放在
// 「今天觉得自己在毁掉生活」/「这一年我什么都没做成」的语境下念出来，残忍就是不合格。

export type PeriodType = 'week' | 'month' | 'year'

const QUESTIONS: Record<PeriodType, string[]> = {
  week: [
    '这周哪个时刻，你觉得「这才是我想要的生活」？',
    '有没有一件小事，做完之后心里松了一口气？',
    '这周你在哪片花瓣上花的心思最多？它回应你了吗？',
    '如果重来一次，这周你会少做什么？',
    '这周有没有一个瞬间，你为自己感到骄傲——哪怕很小？',
    '下周只做一件事的话，你想把水浇在哪片花瓣上？',
  ],
  month: [
    '如果这个月是一章书，你会给它起什么标题？',
    '有什么是月初的你不知道、现在的你知道的？',
    '这个月你放下了什么？放下之后感觉如何？',
    // ↓ 换掉的三题（书香第四轮筛）：
    //   「这个月最出乎意料的一件事」—— 搬得动（换成周或年都成立），泛问
    //   「哪片花瓣悄悄长大了？**你是怎么做到的**？」—— 「做到」**预设了成就**
    //   「下个月只许一个愿望」—— 搬得动，而且它是许愿不是回顾
    '这个月里，有哪一件事你以为会很重要，结果并没有？',
    '如果把这个月分成前半和后半，中间发生了什么？',
    // 措辞改过两版：不写「一直往后挪」，写「**没排上**」——
    //   「挪」是意志失败，「排不上」是光不够。后者才是这产品的立论，而且它不让人难受。
    '这个月有没有一件事，你一直想做，一直没排上？',
  ],
  year: [
    // 🔴 第一位是刻意的（Lisa：全库最好的一句）：它把「没做成」和「责怪」解绑，
    //   预设的是"你不打算责怪自己"。年回顾的第一眼该先递这一句。
    '有什么事今年没做成，但你已经不打算责怪自己了？',
    '如果今年是一本书，封面上会画什么？',
    '今年你最想感谢谁——包括你自己？',
    '明年这朵花，你最想看到哪片花瓣盛放？',
    // ↓ 换掉 / 改过的两题：
    //   ❌ 删「今年的你和去年的你，**最大的不同**是什么？」——
    //      预设"应该有不同"，觉得自己原地踏步的人会答出"没什么不同"，
    //      而那个答案会被他自己读成判决。而且它就是**年度同比的文字版**，同比图早已被否决。
    //   ⚠️ 改「今年哪个决定，现在回头看特别**庆幸**？」——
    //      预设"有值得庆幸的决定"，后悔了一整年的人答不上，答不上就是二次伤害。
    //      门槛从"庆幸"降到"没后悔"，答不上的人少得多。
    '今年有哪个决定，你到现在都没后悔？',
    // 具象到极致，绕开总分，而且它会自动钓出真正有分量的那一天 ——
    //   **记得天气，说明那天有重量。**（Lisa 最想给的一题）
    '今年有哪一天，你现在还记得当时的天气？',
    // 「最不后悔」而不是「最满意」：低一档，更真；
    //   而「花掉的时间」是代价语言本身 —— 「最」指向的是一段时间，不是「你」。
    '今年你花掉的时间里，哪一段现在看最不后悔？',
  ],
}

/**
 * 季节性问题（v3.3 T10，报告 §9.2.2，书香供稿）——
 * 同样是回顾，八月和十二月该问的不是同一件事。每季 3 题，并入当期问题池。
 * 仍是本地内置、零 AI；语气红线不变：只有邀请，没有评判与催促。
 */
const SEASONAL: { months: number[]; questions: string[] }[] = [
  {
    months: [2, 3, 4], // 春 3-5 月
    questions: [
      '春天到了，有什么是你想重新开始的？',
      '如果这个春天只种一样东西，你想种什么？',
      '去年这个时候的你，会羡慕现在的你哪一点？',
    ],
  },
  {
    months: [5, 6, 7], // 夏 6-8 月
    questions: [
      '夏天的光很长，你最想把多出来的时间给谁？',
      '这个夏天有没有一个瞬间，你希望它慢一点过去？',
      '天热的时候你更容易对自己失去耐心吗？那时你需要什么？',
    ],
  },
  {
    months: [8, 9, 10], // 秋 9-11 月
    questions: [
      // 原句「秋天适合收获，这一季你最**满意**的一件事」是半刀：
      //   「适合收获」+「最满意」双重预设。改成指向"结果"而不指向"你的满意度"。
      //   同池第二句本来就是这个意思，两句合并成一句，池子不重复。
      '秋天了，这一季有什么是你现在才看出结果的？',
      '如果要给这一年做减法，你最先放下哪一样？',
    ],
  },
  {
    months: [11, 0, 1], // 冬 12-2 月
    questions: [
      '冬天适合向内看，有什么是你想放下的？',
      '这一年里，哪片花瓣其实一直在安静地等你？',
      '如果可以给年初的自己带一句话，你会说什么？',
    ],
  },
]

function seasonalPool(at: number): string[] {
  const m = new Date(at).getMonth()
  return SEASONAL.find(s => s.months.includes(m))?.questions ?? []
}

/**
 * 取本期的 3 个引导问题：按周期序号轮换，同一期内稳定；每期含 1 道当季问题。
 *
 * 🔴 当季问题**只并入月与年，不进周**（书香口径）：
 *   季节说的是三个月的事，把它塞进周回顾，是拿一个大尺度的问句问一个小尺度的账。
 */
export function pickReviewQuestions(period: PeriodType, periodStart: number): string[] {
  const pool = QUESTIONS[period]
  const idx = Math.floor(periodStart / (24 * 60 * 60 * 1000)) % pool.length
  const base = [0, 1].map(i => pool[(idx + i) % pool.length])

  const seasonal = period === 'week' ? [] : seasonalPool(periodStart)
  if (seasonal.length === 0) return [...base, pool[(idx + 2) % pool.length]]
  return [...base, seasonal[idx % seasonal.length]]
}
