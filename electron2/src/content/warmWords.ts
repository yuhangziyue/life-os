/** 简单字符串哈希，保证同一个种子取到同一句（回响可复现、不闪变） */
function hash(s: string): number {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0
  return h
}

/** 按维度名取一句温暖话语；seed 决定取哪句（如 action id / 日期） */
export function pickWarmWord(dimensionName: string, seed: string): WarmWord {
  const pool = WORDS[dimensionName] ?? GENERIC
  return pool[hash(seed) % pool.length]
}

