/**
 * 🔴 对外那句主张 —— **全仓库唯一合法的「写死数字」点**。
 *
 * 第六轮三人围绕它交锋了三轮，最后的分界规则（书香定稿，Lisa 认可）：
 *   **看这个数字在描述「代价的比例」还是「花的构造」。**
 *   比例 ⇒ 修辞，写死，不许动；构造 ⇒ 数据，必须跟着用户的花瓣数走。
 *   验法：把「八」换成「五」，句子对某些用户是不是变成了**在描述别人的花**。是 ⇒ 构造。
 *
 * 这一句承重的是「多 vs 两三」这个**比例**，构造只是载体 ——
 * 换成「五片花瓣，你只能让其中两三片盛开」仍然成立 ⇒ 修辞 ⇒ 原样保留。
 * （试过的替换版本全部更弱：「光只有一份，花瓣却有那么多」把可计算的落差换成了"那么多"，
 *   读者脑子里那一算就是被击中的瞬间，算不了就退回成"有道理"。）
 *
 * 围栏：它**只能出现在「介绍这个产品是什么」的位置**——meta description、manifest、
 * README、关于页顶部。**不得出现在任何以用户当前花园为语境的界面里**（Lisa 第六轮）——
 * 一进那种语境，修辞就自动变成数据。
 */
